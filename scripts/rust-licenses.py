#!/usr/bin/env python3
"""Rewrites the "Rust crates" section of THIRD-PARTY-NOTICES.md from `cargo metadata`.

Lists every crate the app links on any platform (the normal dependencies of the package
`rustradar`, followed through the whole graph; build-only and test-only dependencies and
xtask are left out), with its version, licence expression and source.

    python3 scripts/rust-licenses.py          # from the repository root
"""
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NOTICES = ROOT / "THIRD-PARTY-NOTICES.md"
HEADING = "## Rust crates"

meta = json.loads(subprocess.run(
    ["cargo", "metadata", "--format-version", "1", "--locked"],
    cwd=ROOT, check=True, capture_output=True, text=True).stdout)
packages = {p["id"]: p for p in meta["packages"]}
nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
members = set(meta["workspace_members"])
app = next(i for i in members if packages[i]["name"] == "rustradar")

seen, todo = set(), [app]
while todo:
    node = nodes[todo.pop()]
    for dep in node["deps"]:
        if any(k["kind"] is None for k in dep["dep_kinds"]) and dep["pkg"] not in seen:
            seen.add(dep["pkg"])
            todo.append(dep["pkg"])

rows = sorted(
    (packages[i] for i in seen if i not in members),
    key=lambda p: (p["name"].lower(), p["version"]))
lines = [
    HEADING, "",
    f"Generated by `python3 scripts/rust-licenses.py` from `Cargo.lock`: {len(rows)} crates the app "
    "links on some platform. Each is under the licence named (an `OR` lets you pick one); their "
    "licence texts are in each crate's source.", "",
    "| Crate | Version | Licence | Source |", "|---|---|---|---|",
]
for p in rows:
    licence = p.get("license") or (f"see {p['license_file']}" if p.get("license_file") else "unknown")
    source = p.get("repository") or p.get("homepage") or f"https://crates.io/crates/{p['name']}"
    lines.append(f"| {p['name']} | {p['version']} | {licence.replace('|', '/')} | {source} |")

text = NOTICES.read_text()
head = text.split(HEADING, 1)[0]
NOTICES.write_text(head + "\n".join(lines) + "\n")
unknown = [p["name"] for p in rows if not p.get("license")]
print(f"{NOTICES.name}: {len(rows)} crates" + (f"; no licence field: {', '.join(unknown)}" if unknown else ""),
      file=sys.stderr)
